"""Render reviewed certificate data into native and diagnostic resources, offline."""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
from pathlib import Path


def revocation_keys(snapshot: dict) -> tuple[list[bytes], list[bytes]]:
    """Use the same DER concatenation and SPKI digest as cert_storage."""
    issuer_serial: set[bytes] = set()
    subject_key: set[bytes] = set()
    for record in snapshot["data"]:
        if record.get("deleted"):
            raise ValueError("a packaged snapshot must not contain tombstones")
        if record.get("issuerName") and record.get("serialNumber"):
            issuer_serial.add(base64.b64decode(record["issuerName"], validate=True)
                              + base64.b64decode(record["serialNumber"], validate=True))
        elif record.get("subject") and record.get("pubKeyHash"):
            digest = base64.b64decode(record["pubKeyHash"], validate=True)
            if len(digest) != 32:
                raise ValueError("OneCRL public-key hashes must be SHA-256")
            subject_key.add(base64.b64decode(record["subject"], validate=True) + digest)
        else:
            raise ValueError(f"unrecognized OneCRL record: {record.get('id')}")
    return sorted(issuer_serial), sorted(subject_key)


def security_data_identity(manifest: dict) -> str:
    return hashlib.sha256(json.dumps(manifest, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def render_revocations(snapshot: dict, digest: str, data_identity: str) -> str:
    tables = []
    for name, keys in zip(("kIssuerSerial", "kSubjectKey"), revocation_keys(snapshot)):
        if not keys:
            raise ValueError("a revocation key table is empty")
        rows = []
        for key in keys:
            literal = "".join(f"\\x{byte:02x}" for byte in key)
            rows.append(f'    {{"{literal}", {len(key)}}},')
        tables.append(f"inline constexpr std::string_view {name}[] = {{\n"
                      + "\n".join(rows) + "\n};")
    return """/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/. */
// Generated by generate-certificate-security.py; do not edit.
#ifndef NavisBundledRevocations_h
#define NavisBundledRevocations_h
#include <algorithm>
#include <iterator>
#include <string_view>
namespace mozilla::psm::navis {
""" + (f'inline constexpr char kOneCRLSHA256[] = "{digest}";\n'
       f'inline constexpr char kSecurityDataSHA256[] = "{data_identity}";\n') + "\n".join(tables) + """
inline bool IsBundledRevoked(std::string_view issuerSerial,
                             std::string_view subjectKey) {
  return std::binary_search(std::begin(kIssuerSerial), std::end(kIssuerSerial),
                            issuerSerial) ||
         std::binary_search(std::begin(kSubjectKey), std::end(kSubjectKey),
                            subjectKey);
}
}  // namespace mozilla::psm::navis
#endif
"""


def render_metadata(manifest: dict) -> str:
    data = {
        "ctExpiration": manifest["ct"]["expires_at"],
        "ctSHA256": manifest["ct"]["sha256"],
        "onecrlTimestamp": manifest["onecrl"]["timestamp"],
        "onecrlSHA256": manifest["onecrl"]["sha256"],
        "trustSHA256": manifest["trust"]["sha256"],
    }
    return ("/* SPDX-License-Identifier: MPL-2.0 */\n"
            "// Generated by generate-certificate-security.py; do not edit.\n"
            "export const CERTIFICATE_SECURITY_DATA = Object.freeze("
            + json.dumps(data, indent=2) + ");\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    runtime = Path(__file__).resolve().parents[1]
    parser.add_argument("--gecko", type=Path, default=runtime / "gecko")
    parser.add_argument("--write", action="store_true", help="write generated resources")
    args = parser.parse_args()
    manifest = json.loads((runtime / "config/certificate-security-data.json").read_text())
    snapshot = json.loads((args.gecko / manifest["onecrl"]["path"]).read_text())
    outputs = {
        args.gecko / "security/certverifier/NavisBundledRevocations.h":
            render_revocations(snapshot, manifest["onecrl"]["sha256"], security_data_identity(manifest)),
        runtime / "embedder/modules/CertificateSecurityData.sys.mjs": render_metadata(manifest),
    }
    for path, expected in outputs.items():
        if args.write:
            path.write_text(expected, encoding="utf-8")
        elif path.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"generated certificate data differs: {path}")
    print("Certificate security resources match the reviewed offline inputs")


if __name__ == "__main__":
    main()
